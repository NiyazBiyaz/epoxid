using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Epoxid.SourceGeneration;

public abstract class BaseGenerator<TTarget> : IIncrementalGenerator
    where TTarget : IEquatable<TTarget>
{
    protected abstract string AttributeMetadataName { get; }

    protected abstract TTarget? CreateTarget(GeneratorAttributeSyntaxContext context, CancellationToken ct);

    protected abstract string Generate(SourceBuilder builder, TTarget target);

    protected const string GeneratedCodeAttribute = "[global::System.CodeDom.Compiler.GeneratedCode(\"Epoxid.SourceGeneration\", null)]";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var pipeline = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeMetadataName,
                predicate: IsGeneratorCandidate,
                transform: CreateTarget)
            .Where(static target => target != null);

        context.RegisterSourceOutput(pipeline, emitFile!);
    }

    // Generic predicate for the class declarations with required partial modifier
    protected virtual bool IsGeneratorCandidate(SyntaxNode node, CancellationToken ct)
    {
        if (node is not ClassDeclarationSyntax cl)
            return false;

        if (!cl.Modifiers.Any(SyntaxKind.PartialKeyword))
            return false;

        return true;
    }

    protected static string GetAccessibilityString(Accessibility accessibility) => accessibility switch
    {
        Accessibility.NotApplicable => "",
        Accessibility.Private => "private",
        Accessibility.ProtectedAndInternal => "private protected",
        Accessibility.Protected => "protected",
        Accessibility.Internal => "internal",
        Accessibility.ProtectedOrInternal => "protected internal",
        Accessibility.Public => "public",

        _ => throw new InvalidOperationException(),
    };

    private void emitFile(SourceProductionContext context, TTarget target)
    {
        var builder = new SourceBuilder();

        builder.AddLines($"""
        // <auto-generated />
        // Bau bau software engineering

        #nullable enable
        """);

        string hintName = Generate(builder, target);

        context.AddSource(hintName, SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}
